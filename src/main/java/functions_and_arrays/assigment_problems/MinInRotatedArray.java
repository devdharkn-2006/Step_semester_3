package functions_and_arrays.assigment_problems;

public class MinInRotatedArray {

    // Key idea: compare mid with the rightmost element. If nums[mid] > nums[hi] the drop
    // (the minimum) is to the right of mid; otherwise mid itself may be the minimum, so keep it.
    static int findMin(int[] nums) {
        int lo = 0, hi = nums.length - 1;
        while (lo < hi) {
            int mid = lo + (hi - lo) / 2;
            if (nums[mid] > nums[hi]) {
                lo = mid + 1;
            } else {
                hi = mid;
            }
        }
        return nums[lo];
    }

    public static void main(String[] args) {
        System.out.println(findMin(new int[]{3, 4, 5, 1, 2}));
        System.out.println(findMin(new int[]{4, 5, 6, 7, 0, 1, 2}));
        System.out.println(findMin(new int[]{11, 13, 15, 17}));
    }
}
